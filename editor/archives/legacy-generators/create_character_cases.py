"""Build two real editable cursor themes from transparent generated artwork.

Only layout/scaling and functional cursor glyphs are composed here; character
art is generated by imagegen. Never installs or activates system pointers.
"""
import argparse
import hashlib
import json
import sys
import tempfile
import zipfile
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

EDITOR_ROOT=Path(__file__).resolve().parents[1]
ROOT=EDITOR_ROOT.parent
sys.path.insert(0,str(EDITOR_ROOT/'src'))
from cursor_studio.models import Theme,Role,Frame,ROLES
from cursor_studio.services.project import save_project,load_project
from cursor_studio.services.export import export_theme
from cursor_studio.io.cur import decode_cur
from cursor_studio.io.ani import decode_ani
from cursor_studio.windows.native import validate_cursor_file
from create_demo import role_art

def build(name,slug,source,color):
    slug += '-v2'
    directory=ROOT/'examples'/slug
    directory.mkdir(parents=True,exist_ok=True)
    if (directory/'theme.json').exists():raise FileExistsError(directory/'theme.json')
    im=Image.open(source).convert('RGBA')
    if im.getextrema()[3][0]!=0:raise ValueError('角色素材没有透明背景')
    im.save(directory/'角色原图.png')
    artwork=im.crop(im.getchannel('A').getbbox())
    theme=Theme(name=name,author='Custom Cursor Studio 案例',description='AI 生成角色同人素材；本地个人主题案例。角色权利属于原权利人。功能符号与角色分离，热点固定在实际指向符号。动态采用角色轻浮动和忙碌环，不是角色表情逐帧重绘。',canvas_size=64)
    for key in ROLES:
        frames=[]
        animated=key in ('Arrow','AppStarting','Wait','Hand')
        for step in range(4 if animated else 1):
            symbol,hotspot=role_art(key,step if key in ('AppStarting','Wait') else 0)
            if key in ('Arrow','Help','AppStarting'):
                symbol=Image.new('RGBA',(64,64));pen=ImageDraw.Draw(symbol)
                pen.polygon([(5,4),(5,48),(17,37),(27,57),(36,52),(25,32),(46,32)],fill=(*color,255),outline='#392d2c',width=3)
                hotspot=(5,4)
                if key=='Help':pen.text((39,42),'?',fill='#392d2c',stroke_width=1)
                if key=='AppStarting':pen.arc((36,38,61,62),step*90,step*90+230,fill='#392d2c',width=4)
            pixels=symbol.load()
            for y in range(64):
                for x in range(64):
                    if pixels[x,y][:3]==(155,232,210):pixels[x,y]=(*color,pixels[x,y][3])
            out=Image.new('RGBA',(64,64))
            if key=='Wait':
                out.alpha_composite(symbol)
                char=artwork.copy();char.thumbnail((30,30),Image.Resampling.LANCZOS)
                out.alpha_composite(char,((64-char.width)//2,(64-char.height)//2))
            else:
                char=artwork.copy();char.thumbnail((48,48),Image.Resampling.LANCZOS)
                dy=[0,-1,-2,-1][step] if animated else 0
                out.alpha_composite(char,(64-char.width,64-char.height+dy))
                # Foreground function glyph has a transparent surround and stays fixed.
                out.alpha_composite(symbol.resize((32,32),Image.Resampling.LANCZOS),(0,0))
                hotspot=tuple(round(v*32/64) for v in hotspot)
            frames.append(Frame(out,hotspot,[400,100,100,200][step] if animated else 100))
        theme.roles[key]=Role(frames=frames,size=64)
    project=save_project(theme,directory/'theme.json')
    reopened=load_project(project)
    for k in ROLES:
        for a,b in zip(theme.roles[k].frames,reopened.roles[k].frames):
            assert a.image.tobytes()==b.image.tobytes() and a.hotspot==b.hotspot and a.duration_ms==b.duration_ms
    archive=export_theme(reopened,directory/(name+'.zip'))
    results=[]
    native=directory/'Windows主题';native.mkdir()
    with zipfile.ZipFile(archive) as z:
        for member in z.namelist():
            # Names come exclusively from our exporter, no untrusted extraction.
            (native/member).write_bytes(z.read(member))
            if member.endswith(('.cur','.ani')):
                p=native/member
                frames=(decode_ani if p.suffix=='.ani' else decode_cur)(p.read_bytes())
                assert validate_cursor_file(p)
                results.append({'file':member,'frames':len(frames),'hotspots':[f.hotspot for f in frames],'native_load':True})
    (directory/'打开此案例.cmd').write_text('@echo off\ncd /d "%~dp0..\\.."\nset "PYTHONPATH=%CD%\\src"\nstart "" ".venv\\Scripts\\pythonw.exe" -m cursor_studio.app "%~dp0theme.json"\n',encoding='ascii')
    (directory/'应用此主题.cmd').write_text('@echo off\ncd /d "%~dp0..\\.."\nset "PYTHONPATH=%CD%\\src"\nstart "" ".venv\\Scripts\\pythonw.exe" -m cursor_studio.ui.theme_launcher "%~dp0theme.json"\n',encoding='ascii')
    (directory/'案例说明.md').write_text(f'# {name}\n\n双击“打开此案例.cmd”在编辑器里预览和修改。\n\n15 状态完整，正常选择、后台运行、忙、链接为四帧动画，其他为静态。画布64像素。箭头尖端/调整线交点/手指尖为实际热点，角色装饰不决定点击位置。\n\n`Windows主题/` 可逐项选择，ZIP 内附 INF 与教程。未安装或切换系统指针。角色为 AI 生成同人素材，请勿冒称官方素材；商用前确认授权。\n',encoding='utf-8')
    return theme,{'name':name,'project':str(project),'zip':str(archive),'native_results':results,'roundtrip':True,'installed':False}

def main():
    p=argparse.ArgumentParser();p.add_argument('sheep');p.add_argument('bear');args=p.parse_args()
    entries=[build('懒羊羊·奶油午睡','lazy-sheep',args.sheep,(255,215,105)),build('一二·软糖白熊','yier-bear',args.bear,(248,168,190))]
    font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',18)
    board=Image.new('RGB',(1120,670),'#f3f1f7');d=ImageDraw.Draw(board)
    for col,(theme,evidence) in enumerate(entries):
        ox=col*560;d.text((ox+24,20),theme.name,font=font,fill='#443855')
        for index,(key,label) in enumerate(ROLES.items()):
            x=ox+24+(index%5)*106;y=72+(index//5)*185
            for yy in range(0,112,14):
                for xx in range(0,98,14):d.rectangle((x+xx,y+yy,x+xx+13,y+yy+13),fill='#ffffff' if (xx//14+yy//14)%2 else '#e3dfeb')
            icon=theme.roles[key].frames[0].image.resize((96,96),Image.Resampling.NEAREST);board.paste(icon,(x,y+8),icon)
            d.text((x,y+122),label,font=font,fill='#443855')
        preview=theme.roles['Arrow'].frames
        preview[0].image.save(Path(evidence['project']).parent/'动画预览.gif',save_all=True,append_images=[f.image for f in preview[1:]],duration=[f.duration_ms for f in preview],loop=0,disposal=2)
    board.save(ROOT/'examples'/'角色案例总览-v2.png')
    baseline=json.loads((EDITOR_ROOT/'evidence/original-sha256.json').read_text('utf-8'))
    assert all(hashlib.sha256((ROOT/k).read_bytes()).hexdigest()==v for k,v in baseline.items())
    (EDITOR_ROOT/'evidence/character-cases-v2.json').write_text(json.dumps({'cases':[e for _,e in entries],'original_hashes_unchanged':True},ensure_ascii=False,indent=2),encoding='utf-8')
    print('Two projects; 30 native-load verified cursors; 8 four-frame animations; original files unchanged.')

if __name__=='__main__':main()
